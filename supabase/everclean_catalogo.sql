-- EVER CLEAN — catálogo e pedidos online
-- Execute uma vez no SQL Editor do projeto Supabase da Ever Clean.

create extension if not exists pgcrypto;

-- Controles do catálogo sobre a tabela de produtos já existente.
alter table public.products add column if not exists catalog_visible boolean not null default true;
alter table public.products add column if not exists catalog_show_price boolean not null default false;
alter table public.products add column if not exists catalog_show_stock boolean not null default true;
alter table public.products add column if not exists catalog_allow_backorder boolean not null default true;

create table if not exists public.ec_order_links (
  id uuid primary key default gen_random_uuid(),
  request_number bigint generated by default as identity unique,
  token text not null unique default encode(gen_random_bytes(24),'hex'),
  customer_id uuid references public.ec_customers(id) on delete set null,
  customer_name text not null default 'Cliente Ever Clean',
  status text not null default 'gerado',
  created_by text,
  seller_name text default 'Guilherme Amaral',
  expires_at timestamptz not null default (now() + interval '7 days'),
  first_opened_at timestamptz,
  submitted_at timestamptz,
  converted_quote_id uuid,
  converted_order_id uuid,
  known_total numeric(12,2) not null default 0,
  items_count integer not null default 0,
  units_count numeric(12,3) not null default 0,
  customer_notes text,
  internal_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ec_order_link_items (
  id uuid primary key default gen_random_uuid(),
  order_link_id uuid not null references public.ec_order_links(id) on delete cascade,
  product_id uuid,
  product_sku text,
  product_name text not null,
  product_image_url text,
  unit text,
  requested_quantity numeric(12,3) not null check (requested_quantity > 0),
  stock_snapshot numeric(12,3),
  available_at_submission numeric(12,3),
  price_visible boolean not null default false,
  unit_price_snapshot numeric(12,2),
  subtotal numeric(12,2),
  price_status text not null default 'sob_consulta',
  fulfillment_status text not null default 'consultar',
  created_at timestamptz not null default now()
);

create index if not exists idx_ec_order_links_token on public.ec_order_links(token);
create index if not exists idx_ec_order_links_customer on public.ec_order_links(customer_id);
create index if not exists idx_ec_order_links_status on public.ec_order_links(status);
create index if not exists idx_ec_order_link_items_link on public.ec_order_link_items(order_link_id);

alter table public.ec_order_links enable row level security;
alter table public.ec_order_link_items enable row level security;

-- Administração: usuários autenticados do ambiente interno podem consultar/atualizar links.
drop policy if exists ec_links_authenticated_select on public.ec_order_links;
create policy ec_links_authenticated_select on public.ec_order_links for select to authenticated using (true);
drop policy if exists ec_links_authenticated_update on public.ec_order_links;
create policy ec_links_authenticated_update on public.ec_order_links for update to authenticated using (true) with check (true);
drop policy if exists ec_items_authenticated_select on public.ec_order_link_items;
create policy ec_items_authenticated_select on public.ec_order_link_items for select to authenticated using (true);

-- Produtos: garante leitura/edição pelo painel interno. Não abre leitura anônima direta.
alter table public.products enable row level security;
drop policy if exists ec_products_authenticated_select on public.products;
create policy ec_products_authenticated_select on public.products for select to authenticated using (true);
drop policy if exists ec_products_authenticated_update on public.products;
create policy ec_products_authenticated_update on public.products for update to authenticated using (true) with check (true);

-- Clientes: leitura pelo painel interno.
alter table public.ec_customers enable row level security;
drop policy if exists ec_customers_authenticated_select on public.ec_customers;
create policy ec_customers_authenticated_select on public.ec_customers for select to authenticated using (true);

-- Criação de link pelo administrador autenticado.
create or replace function public.ec_create_order_link(p_customer_id uuid, p_days integer default 7)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text;
  v_link public.ec_order_links%rowtype;
  v_days integer := greatest(1, least(coalesce(p_days,7),30));
begin
  if auth.uid() is null then
    return jsonb_build_object('ok',false,'message','Acesso não autorizado.');
  end if;

  select coalesce(
    nullif(to_jsonb(c)->>'trade_name',''),
    nullif(to_jsonb(c)->>'company_name',''),
    nullif(to_jsonb(c)->>'name',''),
    nullif(to_jsonb(c)->>'fantasy_name',''),
    'Cliente Ever Clean'
  ) into v_name
  from public.ec_customers c where c.id = p_customer_id;

  if v_name is null then
    return jsonb_build_object('ok',false,'message','Cliente não encontrado.');
  end if;

  insert into public.ec_order_links(customer_id,customer_name,status,created_by,seller_name,expires_at)
  values(p_customer_id,v_name,'gerado',coalesce(auth.jwt()->>'email',auth.uid()::text),'Guilherme Amaral',now() + make_interval(days => v_days))
  returning * into v_link;

  return jsonb_build_object(
    'ok',true,
    'id',v_link.id,
    'token',v_link.token,
    'request_number',v_link.request_number,
    'customer_name',v_link.customer_name,
    'expires_at',v_link.expires_at
  );
end;
$$;

grant execute on function public.ec_create_order_link(uuid,integer) to authenticated;

-- Catálogo público. O cliente recebe apenas os dados necessários e só mediante token longo.
create or replace function public.ec_public_order_catalog(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link public.ec_order_links%rowtype;
  v_products jsonb;
begin
  select * into v_link from public.ec_order_links where token = p_token limit 1;
  if not found then return jsonb_build_object('ok',false,'message','Link inválido.'); end if;

  if v_link.status in ('cancelado','expirado') then
    return jsonb_build_object('ok',false,'message','Este link não está mais disponível.');
  end if;

  if v_link.expires_at < now() and v_link.status not in ('enviado','convertido_orcamento','convertido_pedido') then
    update public.ec_order_links set status='expirado',updated_at=now() where id=v_link.id;
    return jsonb_build_object('ok',false,'message','Este link expirou. Solicite um novo catálogo à Ever Clean.');
  end if;

  if v_link.status = 'gerado' then
    update public.ec_order_links set status='aberto',first_opened_at=coalesce(first_opened_at,now()),updated_at=now() where id=v_link.id;
    v_link.status := 'aberto';
    v_link.first_opened_at := coalesce(v_link.first_opened_at,now());
  end if;

  if v_link.status in ('enviado','convertido_orcamento','convertido_pedido') then
    return jsonb_build_object('ok',true,'link',jsonb_build_object(
      'request_number',v_link.request_number,'customer_name',v_link.customer_name,'status','enviado','expires_at',v_link.expires_at
    ),'products','[]'::jsonb);
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id',p.id,
    'sku',p.sku,
    'name',p.name,
    'brand',p.brand,
    'category',coalesce(p.category,''),
    'unit',p.unit,
    'image_url',p.image_url,
    'base_price',p.base_price,
    'stock_quantity',coalesce(p.stock_quantity,0),
    'catalog_show_price',coalesce(p.catalog_show_price,false),
    'catalog_show_stock',coalesce(p.catalog_show_stock,true),
    'catalog_allow_backorder',coalesce(p.catalog_allow_backorder,true)
  ) order by p.category,p.name),'[]'::jsonb)
  into v_products
  from public.products p
  where coalesce(p.active,true)=true and coalesce(p.catalog_visible,true)=true;

  return jsonb_build_object(
    'ok',true,
    'link',jsonb_build_object(
      'request_number',v_link.request_number,
      'customer_name',v_link.customer_name,
      'status',v_link.status,
      'expires_at',v_link.expires_at,
      'first_opened_at',v_link.first_opened_at
    ),
    'products',v_products
  );
end;
$$;

grant execute on function public.ec_public_order_catalog(text) to anon, authenticated;

-- Envio final. Preços e estoque são recalculados no servidor; o navegador não é fonte confiável.
create or replace function public.ec_submit_order_link(p_token text, p_items jsonb, p_notes text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link public.ec_order_links%rowtype;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty numeric(12,3);
  v_stock numeric(12,3);
  v_subtotal numeric(12,2);
  v_known_total numeric(12,2) := 0;
  v_items_count integer := 0;
  v_units numeric(12,3) := 0;
  v_fulfillment text;
  v_price_status text;
begin
  select * into v_link from public.ec_order_links where token=p_token for update;
  if not found then return jsonb_build_object('ok',false,'message','Link inválido.'); end if;
  if v_link.status in ('enviado','convertido_orcamento','convertido_pedido') then
    return jsonb_build_object('ok',false,'message','Este pedido já foi enviado.');
  end if;
  if v_link.status in ('cancelado','expirado') or v_link.expires_at < now() then
    if v_link.expires_at < now() then update public.ec_order_links set status='expirado',updated_at=now() where id=v_link.id; end if;
    return jsonb_build_object('ok',false,'message','Este link não está mais disponível.');
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then
    return jsonb_build_object('ok',false,'message','Selecione ao menos um produto.');
  end if;

  delete from public.ec_order_link_items where order_link_id=v_link.id;

  for v_item in select * from jsonb_array_elements(p_items) loop
    begin v_qty := greatest(0,(v_item->>'quantity')::numeric); exception when others then v_qty := 0; end;
    if v_qty <= 0 then continue; end if;

    select * into v_product from public.products
    where id=(v_item->>'product_id')::uuid and coalesce(active,true)=true and coalesce(catalog_visible,true)=true;
    if not found then continue; end if;

    v_stock := greatest(0,coalesce(v_product.stock_quantity,0));
    if v_stock >= v_qty then v_fulfillment := 'pronta_entrega';
    elsif v_stock > 0 and coalesce(v_product.catalog_allow_backorder,true) then v_fulfillment := 'parcial';
    elsif coalesce(v_product.catalog_allow_backorder,true) then v_fulfillment := 'sob_encomenda';
    else v_fulfillment := 'consultar'; end if;

    if coalesce(v_product.catalog_show_price,false) and v_product.base_price is not null then
      v_price_status := 'definido';
      v_subtotal := round((v_qty * v_product.base_price)::numeric,2);
      v_known_total := v_known_total + v_subtotal;
    else
      v_price_status := 'sob_consulta'; v_subtotal := null;
    end if;

    insert into public.ec_order_link_items(
      order_link_id,product_id,product_sku,product_name,product_image_url,unit,
      requested_quantity,stock_snapshot,available_at_submission,price_visible,
      unit_price_snapshot,subtotal,price_status,fulfillment_status
    ) values(
      v_link.id,v_product.id,v_product.sku,v_product.name,v_product.image_url,v_product.unit,
      v_qty,v_stock,least(v_stock,v_qty),coalesce(v_product.catalog_show_price,false),
      case when coalesce(v_product.catalog_show_price,false) then v_product.base_price else null end,
      v_subtotal,v_price_status,v_fulfillment
    );
    v_items_count := v_items_count + 1;
    v_units := v_units + v_qty;
  end loop;

  if v_items_count = 0 then return jsonb_build_object('ok',false,'message','Nenhum item válido foi enviado.'); end if;

  update public.ec_order_links set
    status='enviado', submitted_at=now(), known_total=v_known_total,
    items_count=v_items_count, units_count=v_units, customer_notes=nullif(trim(p_notes),''), updated_at=now()
  where id=v_link.id;

  return jsonb_build_object('ok',true,'request_number',v_link.request_number,'known_total',v_known_total,'items_count',v_items_count,'units_count',v_units);
end;
$$;

grant execute on function public.ec_submit_order_link(text,jsonb,text) to anon, authenticated;

